const base = '/dev/module/uji-lokal'
const key = 'cbt:v1:uji-lokal:paket-uji'
async function fixtureQuestion(page: Page, id: string) { const index = await page.evaluate(({key,id}) => localStorage.getItem(key) ? JSON.parse(localStorage.getItem(key)!).order.indexOf(id) : -1, {key,id}); if(index>=0) await number(page,index+1) }
async function begin(page: Page, timed = false, shuffled = false) {
  await page.goto(base)
  if (timed) { await page.getByLabel('Use a timer').check(); await page.getByLabel('Duration', { exact: true }).fill('1') }
  void shuffled // Both orders are always shuffled.
  await page.getByRole('button', { name: 'Start practice', exact: true }).click()
  await expect(page).toHaveURL(new RegExp('/exam$'))
  await fixtureQuestion(page, 'uji-1')
}
async function number(page: Page, n: number) {
  await expect(page.locator('.question-surface')).toBeVisible()
  const toolbar = page.locator('.mobile-exam-toolbar')
  if (await toolbar.isVisible()) { await toolbar.getByRole('button', { name: 'Questions' }).click(); await page.getByRole('dialog').getByRole('button', { name: new RegExp(`^Question ${n},`) }).click() }
  else await page.locator('.exam-sidebar').getByRole('button', { name: new RegExp(`^Question ${n},`) }).click()
}
async function finish(page: Page) {
  await page.getByRole('button', { name: 'Finish practice' }).filter({ visible: true }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByRole('button', { name: 'Submit answers' }).click()
  await expect(page).toHaveURL(/\/results$/)
}
